function mumbaiFix([id, minimumAltitudeFt, maximumAltitudeFt, maximumSpeedKt]: MumbaiFixSpec): ProcedureFixTemplate {
  const geometry = mumbaiFixGeometry[id];
  if (!geometry) throw new Error(`Missing Mumbai geometry for ${id}`);
  return {
    id, bearing: geometry[0], distanceNm: geometry[1],
    ...(minimumAltitudeFt === undefined ? {} : { minimumAltitudeFt }),
    ...(maximumAltitudeFt === undefined ? {} : { maximumAltitudeFt }),
    ...(maximumSpeedKt === undefined ? {} : { maximumSpeedKt }),
  };
}

